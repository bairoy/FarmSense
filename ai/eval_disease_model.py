"""Evaluate the trained classifier on the held-out test split.

    python ai/eval_disease_model.py

Writes ai/METRICS.md. That file is the only place an accuracy number for this
project should be quoted from.

Beyond overall accuracy this reports two things that matter more for a system
that recommends pesticides:

  * Per-class recall. Overall accuracy hides the case where 'healthy' is
    predicted well and 'hispa' is missed half the time — the exact failure
    that costs a farmer a crop.
  * Calibration at the confidence gate. If the model says 0.9 and is right
    only 70% of the time, the gate in config.py is not protecting anyone.
"""

from __future__ import annotations

import json
from collections import defaultdict

import torch

from config import BASE_DIR, CLASSES, CONFIDENCE_GATE, MODEL_PATH
from dataset import SPLIT_RATIOS, SPLIT_SEED, load_splits
from disease_model import build_model

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def collect_predictions(model, loader):
    y_true, y_pred, y_conf = [], [], []

    with torch.no_grad():
        for images, labels in loader:
            probs = torch.softmax(model(images.to(DEVICE)), dim=1)
            confidence, predicted = torch.max(probs, dim=1)

            y_true.extend(labels.tolist())
            y_pred.extend(predicted.cpu().tolist())
            y_conf.extend(confidence.cpu().tolist())

    return y_true, y_pred, y_conf


def confusion_matrix(y_true, y_pred, n):
    matrix = [[0] * n for _ in range(n)]
    for truth, prediction in zip(y_true, y_pred, strict=True):
        matrix[truth][prediction] += 1
    return matrix


def per_class_metrics(matrix):
    """Precision / recall / F1 per class, computed straight from the matrix."""
    results = {}
    for i, name in enumerate(CLASSES):
        true_positive = matrix[i][i]
        predicted_positive = sum(matrix[r][i] for r in range(len(CLASSES)))
        actual_positive = sum(matrix[i])

        precision = true_positive / predicted_positive if predicted_positive else 0.0
        recall = true_positive / actual_positive if actual_positive else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0

        results[name] = {
            "support": actual_positive,
            "precision": round(precision, 4),
            "recall": round(recall, 4),
            "f1": round(f1, 4),
        }
    return results


def calibration(y_true, y_pred, y_conf, bins=5):
    """Bucket predictions by confidence and report accuracy within each bucket.

    A well-calibrated model has accuracy ≈ mean confidence in every bucket.
    """
    buckets = defaultdict(lambda: {"n": 0, "correct": 0, "conf_sum": 0.0})

    for truth, prediction, confidence in zip(y_true, y_pred, y_conf, strict=True):
        index = min(int(confidence * bins), bins - 1)
        bucket = buckets[index]
        bucket["n"] += 1
        bucket["correct"] += int(truth == prediction)
        bucket["conf_sum"] += confidence

    rows = []
    for index in sorted(buckets):
        bucket = buckets[index]
        rows.append(
            {
                "range": f"{index / bins:.1f}-{(index + 1) / bins:.1f}",
                "n": bucket["n"],
                "accuracy": round(bucket["correct"] / bucket["n"], 4),
                "mean_confidence": round(bucket["conf_sum"] / bucket["n"], 4),
            }
        )
    return rows


def gate_effect(y_true, y_pred, y_conf):
    """What the confidence gate actually buys us on the test set."""
    above = [
        (t, p)
        for t, p, c in zip(y_true, y_pred, y_conf, strict=True)
        if c >= CONFIDENCE_GATE
    ]
    below = len(y_true) - len(above)

    accuracy_above = (
        sum(t == p for t, p in above) / len(above) if above else 0.0
    )
    return {
        "gate": CONFIDENCE_GATE,
        "passed": len(above),
        "withheld": below,
        "withheld_pct": round(100 * below / len(y_true), 2),
        "accuracy_above_gate": round(accuracy_above, 4),
    }


def main() -> None:
    _train, _val, test_loader, _classes = load_splits(batch_size=32)

    model = build_model()
    model.load_state_dict(torch.load(MODEL_PATH, map_location=DEVICE))
    model.to(DEVICE).eval()

    y_true, y_pred, y_conf = collect_predictions(model, test_loader)

    matrix = confusion_matrix(y_true, y_pred, len(CLASSES))
    accuracy = sum(t == p for t, p in zip(y_true, y_pred, strict=True)) / len(y_true)
    classes = per_class_metrics(matrix)
    gate = gate_effect(y_true, y_pred, y_conf)
    bins = calibration(y_true, y_pred, y_conf)

    lines = [
        "# Rice Disease Model — Evaluation",
        "",
        "Generated by `ai/eval_disease_model.py`. Do not edit by hand.",
        "",
        "## Setup",
        "",
        "- Architecture: ResNet-18, ImageNet-pretrained, 4-way head",
        (
            f"- Split: {SPLIT_RATIOS[0]:.0%} train / {SPLIT_RATIOS[1]:.0%} val / "
            f"{SPLIT_RATIOS[2]:.0%} test, seed {SPLIT_SEED}"
        ),
        f"- Test images: {len(y_true)}",
        "",
        "## Headline",
        "",
        f"**Test accuracy: {accuracy:.2%}**",
        "",
        "## Per-class",
        "",
        "| class | support | precision | recall | F1 |",
        "|---|---|---|---|---|",
    ]
    for name, metric in classes.items():
        lines.append(
            f"| {name} | {metric['support']} | {metric['precision']:.3f} | "
            f"{metric['recall']:.3f} | {metric['f1']:.3f} |"
        )

    lines += ["", "## Confusion matrix", "", "Rows = truth, columns = prediction.", ""]
    lines.append("| |" + "|".join(CLASSES) + "|")
    lines.append("|---|" + "---|" * len(CLASSES))
    for i, name in enumerate(CLASSES):
        lines.append(f"| **{name}** |" + "|".join(str(v) for v in matrix[i]) + "|")

    lines += [
        "",
        "## Confidence gate",
        "",
        f"The service withholds a treatment recommendation below {gate['gate']:.2f}.",
        "",
        (
            f"- Predictions passing the gate: {gate['passed']} "
            f"({100 - gate['withheld_pct']:.1f}%)"
        ),
        (
            f"- Withheld (farmer asked for another photo): {gate['withheld']} "
            f"({gate['withheld_pct']:.1f}%)"
        ),
        f"- Accuracy among predictions that passed: {gate['accuracy_above_gate']:.2%}",
        "",
        "## Calibration",
        "",
        "| confidence | n | accuracy | mean confidence |",
        "|---|---|---|---|",
    ]
    for row in bins:
        lines.append(
            f"| {row['range']} | {row['n']} | {row['accuracy']:.3f} | "
            f"{row['mean_confidence']:.3f} |"
        )

    lines += [
        "",
        "If accuracy sits well below mean confidence in the top bucket, the model is",
        "overconfident and `CONFIDENCE_GATE` in `ai/config.py` must be raised.",
        "",
    ]

    (BASE_DIR / "METRICS.md").write_text("\n".join(lines))
    (BASE_DIR / "eval_results.json").write_text(
        json.dumps(
            {
                "accuracy": accuracy,
                "per_class": classes,
                "confusion_matrix": matrix,
                "gate": gate,
                "calibration": bins,
            },
            indent=2,
        )
    )

    print(f"Test accuracy {accuracy:.2%} -> wrote ai/METRICS.md")


if __name__ == "__main__":
    main()
